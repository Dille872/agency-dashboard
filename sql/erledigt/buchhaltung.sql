  (select count(*) from information_schema.tables where table_schema = 'public' and table_name = 'chatter_abrechnungen') as tabelle,
  (select not public from storage.buckets where id = 'rechnungen') as bucket_privat,
  (select count(*) from pg_policies where schemaname = 'storage' and policyname like 'rechnungen_%') as speicher_regeln;
